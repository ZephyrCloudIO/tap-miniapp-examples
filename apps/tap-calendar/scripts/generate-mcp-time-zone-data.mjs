import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const momentTimezone = require("moment-timezone/moment-timezone-utils");
const packedTimeZones = require("moment-timezone/data/packed/latest.json");

const FIRST_YEAR = 2020;
const LAST_YEAR = 2100;
const outputUrl = new URL(
  "../src/mcp/time-zone-data.generated.ts",
  import.meta.url,
);

function createFilteredData() {
  const unpacked = {
    version: packedTimeZones.version,
    zones: packedTimeZones.zones.map(momentTimezone.tz.unpack),
    links: packedTimeZones.links,
    countries: [],
  };
  const filtered = momentTimezone.tz.filterLinkPack(
    unpacked,
    FIRST_YEAR,
    LAST_YEAR,
  );
  const zoneNames = new Set(filtered.zones.map(zone => zone.split("|")[0]));
  const targetsByAlias = new Map(filtered.links.map(link => {
    const [target, alias] = link.split("|");
    return [alias, target];
  }));
  const links = filtered.links.map(link => {
    const [, alias] = link.split("|");
    let target = targetsByAlias.get(alias);
    const visited = new Set([alias]);
    while (target && !zoneNames.has(target)) {
      if (visited.has(target)) {
        throw new Error(`Cyclic time-zone alias detected for ${alias}.`);
      }
      visited.add(target);
      target = targetsByAlias.get(target);
    }
    if (!target) {
      throw new Error(`Time-zone alias ${alias} has no canonical zone.`);
    }
    return `${target}|${alias}`;
  });
  return { ...filtered, links };
}

function renderGeneratedModule(data) {
  return `// Generated by scripts/generate-mcp-time-zone-data.mjs. Do not edit by hand.
// Source: moment-timezone ${data.version}; bounded to ${FIRST_YEAR}-${LAST_YEAR} for the MCP isolate.

export const MCP_TIME_ZONE_DATA_VERSION = ${JSON.stringify(data.version)};
export const MCP_TIME_ZONE_DATA_FIRST_YEAR = ${FIRST_YEAR};
export const MCP_TIME_ZONE_DATA_LAST_YEAR = ${LAST_YEAR};

export const MCP_TIME_ZONE_DATA = ${JSON.stringify({
    zones: data.zones,
    links: data.links,
  }, null, 2)} as const;
`;
}

const data = createFilteredData();
if (typeof data.version !== "string" || data.version.length === 0) {
  throw new Error("moment-timezone did not provide a TZDB version.");
}
if (data.zones.length === 0 || data.links.length === 0) {
  throw new Error("Filtered time-zone data is unexpectedly empty.");
}

const generated = renderGeneratedModule(data);
if (process.argv.includes("--check")) {
  const existing = await readFile(outputUrl, "utf8").catch(() => "");
  if (existing !== generated) {
    throw new Error(
      "MCP time-zone data is stale. Run scripts/generate-mcp-time-zone-data.mjs.",
    );
  }
} else {
  await writeFile(outputUrl, generated, "utf8");
}

console.log(
  `MCP time-zone data ${data.version}: ${data.zones.length} zones, ${data.links.length} links (${FIRST_YEAR}-${LAST_YEAR}).`,
);
