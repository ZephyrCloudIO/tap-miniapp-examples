import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const devVarsUrl = new URL('../.dev.vars', import.meta.url);
const devVarsPath = fileURLToPath(devVarsUrl);

if (!existsSync(devVarsPath)) {
  const ticketSecret = randomBytes(32).toString('base64url');
  writeFileSync(
    devVarsPath,
    `# Generated by pnpm predev; loaded only by local Wrangler.\nTICKET_SECRET="${ticketSecret}"\n`,
    { encoding: 'utf8', flag: 'wx', mode: 0o600 },
  );
  console.log('Generated an ignored .dev.vars with a random local ticket secret.');
  process.exit(0);
}

const existing = readFileSync(devVarsPath, 'utf8');
const match = existing.match(/^\s*TICKET_SECRET\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s#]+))/mu);
const ticketSecret = match?.[1] ?? match?.[2] ?? match?.[3] ?? '';
if (ticketSecret.length < 16) {
  throw new Error(
    '.dev.vars must define TICKET_SECRET with at least 16 characters before local development can start.',
  );
}
